test("transições entre páginas: animações, retorno e movimento reduzido", async ({ page }) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.addInitScript(() => {
    window.routeTransitions = [];
    const nativeTransition = document.startViewTransition?.bind(document);
    if (!nativeTransition) return;
    document.startViewTransition = (...args) => {
      const transition = nativeTransition(...args);
      transition.ready.then(() => {
        window.routeTransitions.push({
          kind: document.querySelector(".page-motion")?.dataset.pageKind,
          animations: document.getAnimations().map(animation => animation.animationName).filter(Boolean),
        });
      }).catch(() => {});
      return transition;
    };
  });
  await page.goto("/");
  const navigation = page.getByRole("navigation", { name: "Navegação principal", exact: true });
  await navigation.getByRole("link", { name: "Privacidade", exact: true }).click();
  await expect(page).toHaveURL(/consultoria-em-privacidade$/);
  await expect.poll(() => page.evaluate(() => window.routeTransitions.some(item => item.kind === "marketing" && item.animations.includes("page-arrive")))).toBe(true);
  await navigation.getByRole("link", { name: "Hub Educacional", exact: true }).click();
  await expect(page).toHaveURL(/hub-educacional$/);
  await expect.poll(() => page.evaluate(() => window.routeTransitions.some(item => item.kind === "learning" && item.animations.includes("page-discover")))).toBe(true);
  await page.goBack();
  await expect(page).toHaveURL(/consultoria-em-privacidade$/);
  await navigation.getByRole("link", { name: "Contato", exact: true }).click();
  await expect(page).toHaveURL(/contato$/);
  await expect.poll(() => page.evaluate(() => window.routeTransitions.some(item => item.kind === "form" && item.animations.includes("page-focus")))).toBe(true);
  await page.getByLabel("Nome completo").fill("Navegação fluida");
  await page.locator(".site-footer").getByRole("link", { name: "Política de Privacidade", exact: true }).click();
  await expect(page).toHaveURL(/politica-de-privacidade$/);
  await expect.poll(() => page.evaluate(() => window.routeTransitions.some(item => item.kind === "reading" && item.animations.includes("page-read")))).toBe(true);
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.evaluate(() => { window.routeTransitions = []; });
  await navigation.getByRole("link", { name: "Hub Educacional", exact: true }).click();
  await expect(page).toHaveURL(/hub-educacional$/);
  await expect(page.locator(".page-motion")).toHaveAttribute("data-page-kind", "learning");
  await expect.poll(() => page.evaluate(() => getComputedStyle(document.querySelector(".page-hero__inner>div")).animationName)).toBe("none");
  expect(await page.evaluate(() => window.routeTransitions.every(item => item.animations.length === 0))).toBe(true);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Abrir menu", exact: true }).click();
  await navigation.getByRole("link", { name: "Sobre", exact: true }).click();
  await expect(page).toHaveURL(/sobre$/);
  await expect(page.getByRole("button", { name: "Abrir menu", exact: true })).toHaveAttribute("aria-expanded", "false");
  expect(errors).toEqual([]);
});

