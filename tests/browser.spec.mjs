test("carrossel permite arrastar sem abrir links e navegar pelo teclado", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  const carousel = page.getByRole("region", { name: "Serviços em destaque" });
  const viewport = carousel.locator('.services-carousel__viewport');
  await expect(carousel.locator('.services-carousel__track')).toHaveAttribute('aria-live', 'polite');
  await expect(page.getByRole('button', { name: /Serviço anterior|Próximo serviço|Pausar carrossel/ })).toHaveCount(0);
  await carousel.scrollIntoViewIfNeeded();
  const link = carousel.locator('.services-carousel__slide:not([inert]) a');
  const box = await link.boundingBox();
  await page.mouse.move(box.x + box.width * .8, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .2, box.y + box.height / 2, { steps: 12 });
  await page.mouse.up();
  await expect(page).toHaveURL(/\/$/);
  await expect(carousel.locator('[aria-current="true"]')).toHaveAttribute('aria-label', 'Mostrar serviços a partir do 2');
  await viewport.focus();
  await page.keyboard.press('ArrowRight');
  await expect(carousel.locator('[aria-current="true"]')).toHaveAttribute('aria-label', 'Mostrar serviços a partir do 3');
  await page.keyboard.press('ArrowLeft');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(carousel.locator('[aria-current="true"]')).toHaveAttribute('aria-label', 'Mostrar serviços a partir do 1');
  await viewport.dispatchEvent('pointerdown', { pointerId: 7, pointerType: 'touch', isPrimary: true, button: 0, clientX: 300, clientY: 200 });
  // A vertical gesture must remain available for scrolling the page.
  await viewport.dispatchEvent('pointermove', { pointerId: 7, pointerType: 'touch', isPrimary: true, clientX: 295, clientY: 280 });
  await expect(carousel.locator('[aria-current="true"]')).toHaveAttribute('aria-label', 'Mostrar serviços a partir do 1');
  await expect(viewport).not.toHaveClass(/is-dragging/);
  await viewport.scrollIntoViewIfNeeded();
  const touchBox = await viewport.boundingBox();
  const touchX = touchBox.x + touchBox.width * .8;
  const touchY = touchBox.y + 70;
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: touchX, y: touchY }] });
  for (let step = 1; step <= 10; step++) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: touchX - step * 15, y: touchY }] });
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect(carousel.locator('[aria-current="true"]')).toHaveAttribute('aria-label', 'Mostrar serviços a partir do 2');
  await carousel.getByRole('button', { name: 'Mostrar serviços a partir do 1' }).click();
  await link.click();
  await expect(page).toHaveURL(/consultoria-em-privacidade/);
});
